export function locale() {
  return document.documentElement.lang === "en" ? "en" : "tr";
}

function interpolate(template, params) {
  return template.replace(/\{(\w+)\}/g, (match, key) =>
    Object.hasOwn(params, key) ? String(params[key]) : match,
  );
}

export function t(key, params = {}) {
  const template = messages[locale()][key] ?? messages.tr[key] ?? key;
  return interpolate(template, params);
}

export function tp(key, count, params = {}) {
  const rule = new Intl.PluralRules(locale()).select(Number(count));
  const resolved = messages[locale()][`${key}.${rule}`]
    ? `${key}.${rule}`
    : `${key}.other`;
  return t(resolved, { ...params, count });
}

export function translateDocument(root = document) {
  root.querySelectorAll("[data-i18n]").forEach((element) => {
    element.textContent = t(element.dataset.i18n);
  });
  for (const attribute of ["aria-label", "placeholder", "title"]) {
    const datasetKey = `i18n${attribute
      .split("-")
      .map((part) => part[0].toUpperCase() + part.slice(1))
      .join("")}`;
    root
      .querySelectorAll(`[data-i18n-${attribute}]`)
      .forEach((element) =>
        element.setAttribute(attribute, t(element.dataset[datasetKey])),
      );
  }
}
